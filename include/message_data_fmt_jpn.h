#define TOKENS JPN_WORD(0x021D)
#define POINTS_TENS JPN_WORD(0x021E)
#define POINTS_THOUSANDS JPN_WORD(0x021F)
#define INPUT_DOGGY_RACETRACK_BET JPN_WORD(0x0220)
#define INPUT_BOMBER_CODE JPN_WORD(0x0221)
#define PAUSE_MENU JPN_WORD(0x0222)
#define TIME_SPEED JPN_WORD(0x0223)
#define OWL_WARP JPN_WORD(0x0224)
#define INPUT_LOTTERY_CODE JPN_WORD(0x0225)
#define SPIDER_HOUSE_MASK_CODE JPN_WORD(0x0226)
#define STRAY_FAIRIES_LEFT_WOODFALL JPN_WORD(0x0227)
#define STRAY_FAIRIES_LEFT_SNOWHEAD JPN_WORD(0x0228)
#define STRAY_FAIRIES_LEFT_GREAT_BAY JPN_WORD(0x0229)
